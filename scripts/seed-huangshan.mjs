/**
 * Generate Huangshan literary tour data and write to Supabase.
 * Based on Chinese textbook content: 《黄山奇石》《爬天都峰》《黄山记》+ Li Bai poems
 */
const TOKEN = process.env.SUPABASE_PAT;
const REF = 'qxunedraoviaonjdanag';
const API = `https://api.supabase.com/v1/projects/${REF}/database/query`;
const TOUR_ID = '1baca791-416e-4c72-8fed-3f59001369bf';

async function query(sql) {
  const res = await fetch(API, {
    method: 'POST',
    headers: { 'Authorization': `Bearer ${TOKEN}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ query: sql }),
  });
  if (!res.ok) { const t = await res.text(); throw new Error(`${res.status}: ${t.substring(0,300)}`); }
  return res.json();
}

